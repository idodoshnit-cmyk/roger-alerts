"""research-arch: regenerate the 'checked buildings' table in docs/research/ARCHITECTURE_KIFISIA.md from gk3/data/buildings_spec.json."""
import json, os
ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
B = json.load(open(os.path.join(ROOT, 'gk3', 'data', 'buildings_spec.json')))
rows = [v | {'id': k} for k, v in B.items() if not k.startswith('_') and v['confidence'] in ('photo', 'aerial', 'description')]
rows.sort(key=lambda v: (v.get('zoneOrder', 9), v['map']))
L = ['<!-- checked:start (generated by tools/arch/doc_table.py) -->', '', '| map | id | building | conf. | style | levels / height | roof | photo |', '|---|---|---|---|---|---|---|---|']
for v in rows:
    ph = (v.get('photos') or [''])[0].split('/')[-1]
    L.append('| %d | %s | %s | %s | %s%s | %s / %.1f m | %s %s | %s |' % (v['map'], v['id'], (v.get('name') or v.get('addr') or '').replace('|', '/'), v['confidence'], v['style'],
             (' (' + v['styleDetail'] + ')') if v.get('styleDetail') else '', v['levels'], v['heightM'], v['roof'], v['roofColour'], ph))
L += ['', '<!-- checked:end -->']
p = os.path.join(ROOT, 'docs', 'research', 'ARCHITECTURE_KIFISIA.md'); s = open(p).read()
blk = '\n'.join(L)
if '<!-- checked:start' in s:
    a = s.index('<!-- checked:start'); b = s.index('<!-- checked:end -->') + len('<!-- checked:end -->'); s = s[:a] + blk + s[b:]
else:
    s = s.rstrip() + '\n\n## 7. Buildings checked against photos / aerials\n' + blk + '\n'
open(p, 'w').write(s); print(len(rows), 'rows')
